logger = logging.getLogger(__name__)

# Initialize Groq client (reads from env for key)
os.environ["GROQ_API_KEY"] = GROQ_API_KEY
groq_llm = ChatGroq(
    model_name=GROQ_MODEL,
    temperature=GROQ_TEMPERATURE,
    reasoning_effort="none",
    model_kwargs={"include_reasoning": False},
)

import re

def strip_thinking(text: str) -> str:
    """Fallback: strip any <think>...</think> block that slips through,
    in case a given model/provider combo ignores include_reasoning."""
    if not text:
        return text
    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()

# --- Graph state definition ---
# Using a plain dict as state causes each node's return value to overwrite
# existing keys (including "logs"), so only the last node's logs survive.
# TypedDict + Annotated[list, operator.add] makes "logs" accumulate across
# nodes instead of being clobbered.
class GraphState(TypedDict, total=False):
    image_path: Optional[str]
    image_b64: Optional[str]
    client_name: str
    ad_description: str
    platforms: List[str]
    base_caption: str
    scheduled_date: str
    generated_posts: Dict[str, str]
    schedule_time: str
    logs: Annotated[List[str], operator.add]


# --- Node implementations ---
def analyze_image_node(state: dict):
    """
    Fallback image analysis: uses PIL to extract simple metadata and
    asks the groq model to craft a short image-context caption using ad_description.
    (If you later enable a vision LLM like Gemini, replace this node to call it.)
    """
    logs = []
    image_b64 = state.get("image_b64")
    ad_description = state.get("ad_description", "")
    img_meta_text = ""

    if image_b64:
        try:
            image_bytes = base64.b64decode(image_b64)
            img = Image.open(io.BytesIO(image_bytes))
            img_meta_text = f"image width={img.width}, height={img.height}, mode={img.mode}"
            logs.append(f"PIL metadata extracted: {img_meta_text}")
        except Exception as e:
            logs.append(f"Failed to decode/process image: {e}")

    # Compose a prompt for the groq LLM to produce a short "image context" description
    prompt = (
        "You are a marketing assistant. Given the ad description and any basic image metadata, "
        "write one short sentence that describes the visual elements or the vibe of the ad for use in captions.\n\n"
        f"Ad description: {ad_description}\n"
        f"Image metadata: {img_meta_text}\n"
        "Keep it concise and suitable to embed inside social media captions."
    )

    try:
        resp = groq_llm.invoke(prompt)
        base_caption = strip_thinking(resp.content.strip())
        logs.append("Image context generated by Groq.")
    except Exception as e:
        base_caption = f"{ad_description} ({img_meta_text})"
        logs.append(f"Groq image context failed, falling back to metadata: {e}")

    state["base_caption"] = base_caption
    state.setdefault("logs", []).extend(logs)
    return {"base_caption": base_caption, "logs": logs}


def generate_captions_with_groq(state: dict):
    posts: Dict[str, str] = {}
    platforms = state.get("platforms", [])
    client_name = state.get("client_name", "Client")
    ad_description = state.get("ad_description", "")
    base_caption = state.get("base_caption", "")

    logs = []
    if not platforms:
        logs.append("WARNING: 'platforms' was empty when generate node ran; no posts will be created.")

    for platform in platforms:
        prompt = (
            f"Write a high-converting {platform} social post for {client_name}.\n"
            f"Description: {ad_description}\n"
            f"Image context: {base_caption}\n"
            "Make it match the platform tone, include relevant emojis and hashtags as appropriate, "
            "and keep it short enough for the platform."
        )
        try:
            resp = groq_llm.invoke(prompt)
            posts[platform] = strip_thinking(resp.content.strip())
        except Exception as e:
            posts[platform] = f"{ad_description} {base_caption}"
            logs.append(f"Groq generation failed for {platform}: {e}")

    logs.append(f"Generated captions for {len(platforms)} platforms.")
    state["generated_posts"] = posts
    state.setdefault("logs", []).extend(logs)
    return {"generated_posts": posts, "logs": logs}


def scheduler_node(state: dict):
    scheduled_at = state.get("scheduled_date", "ASAP")
    logs = [f"Posts scheduled for {scheduled_at}"]
    state["schedule_time"] = scheduled_at
    state.setdefault("logs", []).extend(logs)
    return {"schedule_time": scheduled_at, "logs": logs}


# --- Build graph once at startup ---
def build_graph():
    workflow_v2 = StateGraph(GraphState)
    workflow_v2.add_node("analyze", analyze_image_node)
    workflow_v2.add_node("generate", generate_captions_with_groq)
    workflow_v2.add_node("scheduler", scheduler_node)

    workflow_v2.set_entry_point("analyze")
    workflow_v2.add_edge("analyze", "generate")
    workflow_v2.add_edge("generate", "scheduler")
    workflow_v2.add_edge("scheduler", END)

    checkpointer = MemorySaver()
    app_v2 = workflow_v2.compile(checkpointer=checkpointer)
    return app_v2

app_v2 = build_graph()

