@api.post("/generate")
async def generate(
    client_name: str = Form(...),
    ad_description: str = Form(...),
    platforms: str = Form(...),  # comma-separated list
    scheduled_date: Optional[str] = Form(None),
    image: Optional[UploadFile] = File(None),
):
    """
    Generate platform-specific posts from an uploaded image and campaign info.

    - client_name: name of the client
    - ad_description: short textual description of ad (product, tagline)
    - platforms: comma-separated list, e.g. "Instagram,LinkedIn"
    - scheduled_date: optional schedule string
    - image: optional image file
    """
    # Read image bytes and convert to base64 if provided
    image_b64 = None
    if image:
        try:
            image_bytes = await image.read()
            image_b64 = base64.b64encode(image_bytes).decode("utf-8")
        except Exception as e:
            raise HTTPException(status_code=400, detail=f"Failed to read uploaded image: {e}")

    platform_list = [p.strip() for p in platforms.split(",") if p.strip()]

    if not platform_list:
        raise HTTPException(
            status_code=400,
            detail=(
                "No valid platforms provided. 'platforms' must be a non-empty "
                "comma-separated string, e.g. 'Instagram,LinkedIn'."
            ),
        )

    inputs = {
        "image_path": None,
        "image_b64": image_b64,
        "client_name": client_name,
        "ad_description": ad_description,
        "platforms": platform_list,
        "base_caption": "",
        "logs": [],
        "scheduled_date": scheduled_date or "ASAP",
    }

    # Unique config/thread id for the run
    config = {"configurable": {"thread_id": str(uuid.uuid4())}}

    try:
        # Stream the workflow to completion
        for _out in app_v2.stream(inputs, config):
            # We don't need to do anything per step; streaming advances the workflow.
            pass

        final_state = app_v2.get_state(config).values
        # final_state should be a dict-like structure
        generated_posts = final_state.get("generated_posts", {})
        schedule_time = final_state.get("schedule_time", final_state.get("scheduled_date", "ASAP"))
        logs = final_state.get("logs", [])

        return JSONResponse({
            "client_name": client_name,
            "generated_posts": generated_posts,
            "schedule_time": schedule_time,
            "logs": logs
        })

    except Exception as e:
        logger.exception("Workflow execution failed")
        raise HTTPException(status_code=500, detail=f"Workflow execution failed: {e}")
